import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import Engine, inspect

from stockpilot.agents.checkpoints import CheckpointStore

pytestmark = pytest.mark.integration

APP_TABLES = {
    "vehicle_models",
    "trims",
    "dealers",
    "units",
    "reservations",
    "sales",
    "unit_events",
    "transfer_orders",
    "agent_runs",
}


def test_models_match_the_latest_migration(migrated_engine: Engine, alembic_config: Config) -> None:
    """Fails if someone changes a model and forgets to generate its migration.

    `alembic check` goes through migrations/env.py, like autogenerate does: with
    LangGraph's checkpoint tables in the database, it must still find nothing.
    """
    _ensure_checkpoint_tables(migrated_engine)

    command.check(alembic_config)  # raises AutogenerateDiffsDetected


def _ensure_checkpoint_tables(engine: Engine) -> None:
    store = CheckpointStore(engine.url.render_as_string(hide_password=False))
    try:
        store.saver()
    finally:
        store.close()


def test_migrations_downgrade_to_empty_and_upgrade_back(
    migrated_engine: Engine, alembic_config: Config
) -> None:
    command.downgrade(alembic_config, "base")
    assert APP_TABLES.isdisjoint(inspect(migrated_engine).get_table_names())

    # Leave the schema at head for the rest of the session.
    command.upgrade(alembic_config, "head")
    assert APP_TABLES.issubset(inspect(migrated_engine).get_table_names())
